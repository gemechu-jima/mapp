export function translateUiText(value: string, language: string): string {
  const text = value.trim();
  if (!text) return value;
  if (language === 'en') return value;
  const entry = uiTranslations[text];
  if (entry) {
    const translated = language === 'am' ? entry.am : language === 'or' ? entry.or : value;
    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    return `${leading}${translated}${trailing}`;
  }
  let translatedValue = value;
  const keys = Object.keys(uiTranslations).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    const phrase = uiTranslations[key];
    const replacement = language === 'am' ? phrase.am : phrase.or;
    if (translatedValue.includes(key)) translatedValue = translatedValue.split(key).join(replacement);
  }
  return translatedValue;
}
